#!/usr/bin/env node
'use strict';

/**
 * Writes the AppStream metainfo the Linux software centres read.
 *
 * A .deb control file has no field for a licence, a developer name, or a
 * release date, which is why Ubuntu's App Center showed "License unknown" and
 * "Last updated Unknown". That information lives in AppStream metadata at
 * /usr/share/metainfo, and electron-builder does not generate it, so this does.
 *
 * Generated rather than committed so the version and date cannot go stale.
 */

const fs = require('node:fs');
const path = require('node:path');

const pkg = require('../package.json');
const REPO = 'https://github.com/meSingh/sukhi-play';
// The site is the front door now, so it is the homepage. The repository stays
// the place to file things and to read the code.
const SITE = 'https://sukhiplay.com';
const RAW = 'https://raw.githubusercontent.com/meSingh/sukhi-play/main';

const escape = (text) => String(text).replace(/[&<>"']/g, (c) => (
  { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' }[c]
));

const today = new Date().toISOString().slice(0, 10);

// Two builds need the same metadata with a different launchable. The .deb
// installs sukhi-play.desktop; Flathub requires the desktop file to be named
// after the app id. Everything else is identical, so it is generated once.
const buildXml = (desktopId) => `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/make-metainfo.js. Do not edit by hand. -->
<component type="desktop-application">
  <id>com.msingh.sukhi.play</id>

  <name>Sukhi Play</name>
  <summary>Let a small child open only the sites you choose</summary>

  <metadata_license>MIT</metadata_license>
  <project_license>MIT</project_license>

  <developer id="com.msingh">
    <name>Mandeep Singh</name>
  </developer>

  <launchable type="desktop-id">${desktopId}</launchable>

  <description>
    <p>
      Sukhi Play turns a computer into a safe place for a small child to play.
      They get a few big buttons, one per site a parent has allowed, and
      nothing else.
    </p>
    <p>
      Everything else is switched off: other websites, advertising, popups, new
      windows, downloads, and the keyboard shortcuts that would otherwise let a
      three-year-old wander into your work. Leaving needs a grown-up.
    </p>
    <p>It ships with nothing enabled. A parent chooses what is allowed:</p>
    <ul>
      <li>Each site gets an allowlist, and anything not essential to it is cut</li>
      <li>Advertising and trackers are blocked on top of that</li>
      <li>No popups, no new windows, no downloads, no navigating away</li>
      <li>Arrow keys and WASD still reach the page, so games still work</li>
      <li>Closing the app needs a three-second press and hold</li>
    </ul>
    <p>
      This is not a substitute for adult supervision. It reduces what a small
      child can reach; it does not childproof a computer.
    </p>
  </description>

  <categories>
    <category>Education</category>
    <category>Game</category>
  </categories>

  <keywords>
    <keyword>kids</keyword>
    <keyword>children</keyword>
    <keyword>parental controls</keyword>
    <keyword>kiosk</keyword>
    <keyword>toddler</keyword>
  </keywords>

  <url type="homepage">${SITE}</url>
  <url type="bugtracker">${REPO}/issues</url>
  <url type="help">${SITE}/debug.html</url>
  <url type="vcs-browser">${REPO}</url>

  <screenshots>
${screenshots()}
  </screenshots>

  <content_rating type="oars-1.1"/>

  <releases>
    <release version="${escape(pkg.version)}" date="${today}">
      <url type="details">${REPO}/releases/tag/v${escape(pkg.version)}</url>
    </release>
  </releases>
</component>
`;

const out = path.join(__dirname, '..', 'build', 'linux');
fs.mkdirSync(out, recursiveOpt());
function screenshots () {
  const dir = path.join(__dirname, '..', 'docs', 'screenshots');
  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(path.join(dir, 'captions.json'), 'utf8'));
  } catch (err) {
    throw new Error(
      'docs/screenshots/captions.json is missing or unreadable. ' +
      'Run `npm run shots` to regenerate the screenshot set. (' + err.message + ')'
    );
  }

  const usable = manifest.filter((s) => !s.error && fs.existsSync(path.join(dir, s.name + '.png')));
  if (!usable.length) throw new Error('no usable screenshots in docs/screenshots');

  // AppStream wants the primary view first. The launcher is what the app is,
  // so it leads regardless of filename order.
  usable.sort((a, b) => (a.name.includes('launcher') ? -1 : b.name.includes('launcher') ? 1 : 0));

  return usable.map((s, i) => {
    const tag = i === 0 ? '<screenshot type="default">' : '<screenshot>';
    return [
      '    ' + tag,
      '      <caption>' + escape(s.caption) + '</caption>',
      '      <image>' + RAW + '/docs/screenshots/' + s.name + '.png</image>',
      '    </screenshot>'
    ].join('\n');
  }).join('\n');
}

const targets = [
  {
    file: path.join(out, 'com.msingh.sukhi.play.metainfo.xml'),
    desktopId: 'sukhi-play.desktop'
  },
  {
    // Committed, because the flatpak build cannot run this script: the
    // freedesktop SDK has no node. CI checks it is not stale.
    file: path.join(__dirname, '..', 'packaging', 'flathub',
      'com.msingh.sukhi.play.metainfo.xml'),
    desktopId: 'com.msingh.sukhi.play.desktop'
  }
];

for (const target of targets) {
  fs.mkdirSync(path.dirname(target.file), recursiveOpt());
  fs.writeFileSync(target.file, buildXml(target.desktopId), 'utf8');
  console.log(`wrote ${path.relative(process.cwd(), target.file)} for version ${pkg.version}`);
}

