#!/usr/bin/env node
'use strict';

/**
 * Writes the winget manifests for a published release.
 *
 * Generated rather than hand-kept, because the one thing a winget manifest
 * cannot survive is a checksum that does not match the file. The installer URL
 * is pinned to the tag, never to /releases/latest/download/: a moving URL
 * breaks the hash on the next release and the package silently stops
 * installing.
 *
 *   node scripts/winget-manifest.js            # the version in package.json
 *   node scripts/winget-manifest.js 1.0.15
 *
 * Nothing here submits anything. Submitting means opening a pull request
 * against microsoft/winget-pkgs, which is a person's job, not a script's.
 */

const fs = require('node:fs');
const path = require('node:path');
const https = require('node:https');

const ROOT = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const version = process.argv[2] || pkg.version;
const tag = `v${version}`;
const REPO = 'https://github.com/meSingh/sukhi-play';
const INSTALLER = 'Sukhi-Play-Windows-Setup.exe';
const SCHEMA = '1.12.0';

function get (url) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'user-agent': 'sukhi-play-manifest' } }, (res) => {
      if (res.statusCode >= 300 && res.headers.location) {
        res.resume();
        return resolve(get(res.headers.location));
      }
      if (res.statusCode !== 200) {
        res.resume();
        return reject(new Error(`${url} returned ${res.statusCode}`));
      }
      let body = '';
      res.setEncoding('utf8');
      res.on('data', (d) => { body += d; });
      res.on('end', () => resolve(body));
    }).on('error', reject);
  });
}

async function main () {
  const sums = await get(`${REPO}/releases/download/${tag}/SHA256SUMS.txt`);
  const line = sums.split('\n').find((l) => l.trim().endsWith(INSTALLER));
  if (!line) throw new Error(`${INSTALLER} is not in SHA256SUMS.txt for ${tag}`);
  const sha = line.trim().split(/\s+/)[0].toUpperCase();

  const out = path.join(ROOT, 'packaging', 'winget', version);
  fs.mkdirSync(out, { recursive: true });

  const head = (type) => `# Generated by scripts/winget-manifest.js. Do not hand-edit.\n` +
    `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${SCHEMA}.schema.json\n\n` +
    `PackageIdentifier: meSingh.SukhiPlay\nPackageVersion: ${version}\n`;

  fs.writeFileSync(path.join(out, 'meSingh.SukhiPlay.installer.yaml'),
    head('installer') +
`InstallerType: nullsoft
Scope: user
InstallModes:
  - interactive
  - silent
  - silentWithProgress
UpgradeBehavior: install
ReleaseDate: ${new Date().toISOString().slice(0, 10)}
Installers:
  - Architecture: x64
    InstallerUrl: ${REPO}/releases/download/${tag}/${INSTALLER}
    InstallerSha256: ${sha}
ManifestType: installer
ManifestVersion: ${SCHEMA}
`);

  fs.writeFileSync(path.join(out, 'meSingh.SukhiPlay.locale.en-GB.yaml'),
    head('defaultLocale') +
`PackageLocale: en-GB
Publisher: Mandeep Singh
PublisherUrl: https://www.msingh.com
PublisherSupportUrl: ${REPO}/issues
PackageName: Sukhi Play
PackageUrl: https://sukhiplay.com/
License: MIT
LicenseUrl: ${REPO}/blob/main/LICENSE
Copyright: Copyright (c) 2026 Mandeep Singh
ShortDescription: A locked-down browser that opens only the websites a grown-up chose.
Description: |-
  Sukhi Play turns a computer into a safe place for a very small child to play.
  A grown-up chooses which websites are allowed. The child gets a full screen of
  large, brightly coloured buttons, one for each approved site, and nothing
  else: no address bar, no tabs, no search, no menus, and no way to reach
  anything you did not put there.

  Play time can be limited to a set number of minutes, after which the child
  sees a stop screen and nothing else opens. Closing the app needs a button
  held down for three seconds, which a toddler does not manage by accident.
  Ads and trackers are filtered out, nothing is uploaded, and there is no
  account to create.
Moniker: sukhi-play
Tags:
  - browser
  - kids
  - kiosk
  - parental-controls
  - screen-time
ReleaseNotesUrl: ${REPO}/releases/tag/${tag}
ManifestType: defaultLocale
ManifestVersion: ${SCHEMA}
`);

  fs.writeFileSync(path.join(out, 'meSingh.SukhiPlay.yaml'),
    head('version') +
`DefaultLocale: en-GB
ManifestType: version
ManifestVersion: ${SCHEMA}
`);

  console.log(`[winget] manifests for ${version} in packaging/winget/${version}`);
  console.log(`[winget] ${INSTALLER} sha256 ${sha}`);
  console.log('[winget] nothing has been submitted; see packaging/winget/README.md');
}

main().catch((err) => {
  console.error(`[winget] ${err.message}`);
  process.exit(1);
});
